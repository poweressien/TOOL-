object Pw {
    private val rnd = SecureRandom()
    private val COMMON = listOf("password", "123456", "qwerty", "letmein", "admin", "welcome", "iloveyou", "monkey", "dragon",
        "football", "abc123", "111111", "login", "passw0rd", "master", "sunshine", "princess", "shadow", "naija", "lagos")
    private val SEQ = listOf("abcd", "1234", "qwer", "asdf", "zxcv", "0000", "1111", "4321", "9876")

    fun generate(len: Int, up: Boolean, low: Boolean, dig: Boolean, sym: Boolean, noAmb: Boolean): String {
        var u = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
        var l = "abcdefghijklmnopqrstuvwxyz"
        var d = "0123456789"
        val s = "!@#$%^&*()-_=+[]{};:,.?"
        if (noAmb) { u = u.filter { it !in "OI" }; l = l.filter { it != 'l' }; d = d.filter { it !in "01" } }
        val pools = listOfNotNull(u.takeIf { up }, l.takeIf { low }, d.takeIf { dig }, s.takeIf { sym }).ifEmpty { listOf(l) }
        val all = pools.joinToString("")
        val chars = MutableList(len) { all[rnd.nextInt(all.length)] }
        pools.forEachIndexed { i, p -> if (i < len) chars[i] = p[rnd.nextInt(p.length)] }
        chars.shuffle(rnd)
        return chars.joinToString("")
    }

    fun entropy(p: String): Double {
        if (p.isEmpty()) return 0.0
        var pool = 0
        if (p.any { it.isLowerCase() }) pool += 26
        if (p.any { it.isUpperCase() }) pool += 26
        if (p.any { it.isDigit() }) pool += 10
        if (p.any { !it.isLetterOrDigit() }) pool += 32
        var bits = p.length * (ln(pool.coerceAtLeast(2).toDouble()) / ln(2.0))
        bits *= (p.toSet().size.toDouble() / p.length).coerceAtLeast(0.4)
        val low = p.lowercase()
        if (COMMON.any { low.contains(it) }) bits -= 15
        if (SEQ.any { low.contains(it) }) bits -= 8
        if (low in COMMON) bits = minOf(bits, 12.0)
        return bits.coerceAtLeast(0.0)
    }

    fun label(bits: Double) = when {
        bits >= 100 -> "Excellent"; bits >= 75 -> "Strong"; bits >= 50 -> "Fair"; bits >= 30 -> "Weak"; else -> "Very weak"
    }

    fun pct(bits: Double) = (bits / 100 * 100).toInt().coerceIn(0, 100)

    fun crackTime(bits: Double): String {
        val secs = 2.0.pow(bits) / 2 / 1e10
        return when {
            secs < 1 -> "instantly"
            secs < 60 -> "${secs.toInt()} seconds"
            secs < 3600 -> "${(secs / 60).toInt()} minutes"
            secs < 86400 -> "${(secs / 3600).toInt()} hours"
            secs < 86400 * 365 -> "${(secs / 86400).toInt()} days"
            secs < 86400.0 * 365 * 1000 -> "${(secs / 86400 / 365).toInt()} years"
            else -> "centuries+"
        }
    }

    fun sha1Hex(s: String): String = MessageDigest.getInstance("SHA-1").digest(s.toByteArray()).joinToString("") { "%02X".format(it) }

    /** k-anonymity: only the first 5 hex chars of the SHA-1 leave the phone. */
    fun pwned(p: String): Int {
        val h = sha1Hex(p)
        val c = URL("https://api.pwnedpasswords.com/range/${h.take(5)}").openConnection() as HttpURLConnection
        c.setRequestProperty("Add-Padding", "true")
        c.connectTimeout = 8000; c.readTimeout = 8000
        val suffix = h.drop(5)
        c.inputStream.bufferedReader().useLines { lines ->
            for (l in lines) {
                val parts = l.split(":")
                if (parts.size == 2 && parts[0].equals(suffix, true)) return parts[1].trim().toIntOrNull() ?: 1
            }
        }
        return 0
    }
}

@Composable
fun PasswordsScreen() {
    val ctx = LocalContext.current
    val scope = rememberCoroutineScope()
    var tab by remember { mutableIntStateOf(0) }
    var len by remember { mutableFloatStateOf(20f) }
    var up by remember { mutableStateOf(true) }
    var low by remember { mutableStateOf(true) }
    var dig by remember { mutableStateOf(true) }
    var sym by remember { mutableStateOf(true) }
    var amb by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf(Pw.generate(20, true, true, true, true, false)) }
    var check by remember { mutableStateOf("") }
    var show by remember { mutableStateOf(false) }
    var breach by remember { mutableStateOf("") }
    var checking by remember { mutableStateOf(false) }

    Column(Modifier.fillMaxSize().padding(14.dp).verticalScroll(rememberScrollState()), verticalArrangement = Arrangement.spacedBy(12.dp)) {
        Text("Passwords", style = MaterialTheme.typography.headlineSmall)
        Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
            FilterChip(selected = tab == 0, onClick = { tab = 0 }, label = { Text("Generator") })
            FilterChip(selected = tab == 1, onClick = { tab = 1 }, label = { Text("Checker + breach") })
        }
        if (tab == 0) {
            Card(Modifier.fillMaxWidth()) {
                Column(Modifier.padding(14.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
                    Text(generated, fontFamily = FontFamily.Monospace, fontSize = 18.sp, fontWeight = FontWeight.Medium)
                    val bits = Pw.entropy(generated)
                    PercentBar(Pw.pct(bits), if (bits >= 75) Color(0xFF34D399) else Color(0xFFFBBF24), 10)
                    Text("${Pw.label(bits)} · ~${bits.toInt()} bits · crack time ${Pw.crackTime(bits)}", style = MaterialTheme.typography.bodySmall)
                    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                        Button(onClick = { generated = Pw.generate(len.toInt(), up, low, dig, sym, amb) }) { Text("Generate") }
                        OutlinedButton(onClick = { copyText(ctx, generated, true) }) { Text("Copy") }
                    }
                }
            }
            Text("Length: ${len.toInt()}")
            Slider(value = len, onValueChange = { len = it; generated = Pw.generate(it.toInt(), up, low, dig, sym, amb) }, valueRange = 8f..64f)
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                FilterChip(selected = up, onClick = { up = !up }, label = { Text("A-Z") })
                FilterChip(selected = low, onClick = { low = !low }, label = { Text("a-z") })
                FilterChip(selected = dig, onClick = { dig = !dig }, label = { Text("0-9") })
                FilterChip(selected = sym, onClick = { sym = !sym }, label = { Text("#$%") })
            }
            FilterChip(selected = amb, onClick = { amb = !amb }, label = { Text("Avoid look-alikes (O 0 I l 1)") })
        } else {
            OutlinedTextField(
                check, { check = it; breach = "" }, label = { Text("Type or paste a password") }, singleLine = true,
                visualTransformation = if (show) VisualTransformation.None else PasswordVisualTransformation(),
                modifier = Modifier.fillMaxWidth()
            )
            FilterChip(selected = show, onClick = { show = !show }, label = { Text("Show") })
            if (check.isNotEmpty()) {
                val bits = Pw.entropy(check)
                Card(Modifier.fillMaxWidth()) {
                    Column(Modifier.padding(14.dp), verticalArrangement = Arrangement.spacedBy(6.dp)) {
                        Text(Pw.label(bits), style = MaterialTheme.typography.titleLarge, fontWeight = FontWeight.Bold,
                            color = if (bits >= 75) Color(0xFF34D399) else if (bits >= 50) Color(0xFFFBBF24) else Color(0xFFEF4444))
                        PercentBar(Pw.pct(bits), if (bits >= 75) Color(0xFF34D399) else if (bits >= 50) Color(0xFFFBBF24) else Color(0xFFEF4444), 10)
                        Text("~${bits.toInt()} bits · estimated crack time at 10 billion guesses/s: ${Pw.crackTime(bits)}", style = MaterialTheme.typography.bodySmall)
                        if (check.length < 12) Text("• Use at least 12 characters", style = MaterialTheme.typography.bodySmall)
                        if (!check.any { it.isDigit() } || !check.any { !it.isLetterOrDigit() }) Text("• Mix digits and symbols", style = MaterialTheme.typography.bodySmall)
                        Text("Estimate only; real attackers also use dictionaries and leaked lists.", style = MaterialTheme.typography.bodySmall)
                    }
                }
                Button(enabled = !checking, onClick = {
                    checking = true; breach = "Checking…"
                    scope.launch {
                        breach = try {
                            val n = withContext(Dispatchers.IO) { Pw.pwned(check) }
                            if (n > 0) "⚠ Found in $n known data breaches. Never use this password." else "✓ Not found in the Have I Been Pwned database."
                        } catch (e: Exception) { "Could not check: ${e.message}" }
                        checking = false
                    }
                }) { Text("Check data breaches") }
                if (breach.isNotEmpty()) Text(breach, fontWeight = FontWeight.Medium)
                Text("Only the first 5 characters of the password's SHA-1 hash are sent (k-anonymity). The password never leaves your phone.", style = MaterialTheme.typography.bodySmall)
            }
        }
    }
}
